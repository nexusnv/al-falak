"""Frozen city lookup table for CLI `--city` (internal only).

Sources (frozen pin as-shipped 2026-10-09):
- OIC capitals (57, deduplicated by normalized key; disputed capitals pinned
  as-shipped) + largest world metros by population (UN World Urbanization
  Prospects, descending) until 300 entries.
- Coordinates: GeoNames wins on disagreement, Natural Earth as fallback;
  retrieval date 2026-10-09. Stored at 4-decimal precision (~11 m, well
  within minute-rounded prayer-output tolerance).

Internal only: NOT exported via `alfalak.__init__.__all__` or
`alfalak.data.__all__`. Library API (`Coordinates`, `PrayerTimes`) is
unchanged; CLI-only lookup.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from types import MappingProxyType
from typing import Mapping

from alfalak.exceptions import ValidationError

_WHITESPACE_RE = re.compile(r"\s+")

_FORMAT_HINT = 'expected NAME,CC, e.g. --city "Kuala Lumpur,MY"'


@dataclass(frozen=True)
class City:
    """Frozen city record (internal)."""

    name: str
    country: str
    latitude: float
    longitude: float
    timezone: str


def normalize_city_key(raw: str) -> str:
    """Normalize `--city` input to `name.lower()+","+cc.upper()`.

    Order per spec: strip, split on last comma, strip parts,
    CC-shape check (2 ASCII alpha, precedence over lookup),
    collapse whitespace runs in name, lower/upper key.
    """
    stripped = raw.strip()
    if "," not in stripped:
        raise ValidationError(f"invalid --city {raw.strip()!r} ({_FORMAT_HINT}).")
    name_part, cc_part = stripped.rsplit(",", 1)
    name_part = name_part.strip()
    cc_part = cc_part.strip()
    if not name_part or not cc_part:
        raise ValidationError(f"invalid --city {raw.strip()!r} ({_FORMAT_HINT}).")
    if len(cc_part) != 2 or not cc_part.isascii() or not cc_part.isalpha():
        raise ValidationError(
            f"invalid --city {raw.strip()!r} "
            f"(country code must be 2 ASCII letters, {_FORMAT_HINT})."
        )
    collapsed = _WHITESPACE_RE.sub(" ", name_part)
    return f"{collapsed.lower()},{cc_part.upper()}"


def resolve_city(raw: str) -> City:
    """Resolve `--city` input to a frozen :class:`City`."""
    key = normalize_city_key(raw)
    try:
        return CITY_TABLE[key]
    except KeyError:
        cc = key.rsplit(",", 1)[1]
        raise ValidationError(
            f"unknown --city {raw.strip()!r} "
            f"(no match; try 'al-falak cities --country {cc}')."
        ) from None


