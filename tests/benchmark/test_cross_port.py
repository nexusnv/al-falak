"""Cross-port benchmark harness (Phase 6.1).

Compares this implementation against vendored reference vectors from two
pinned ports:

- ``adhan_kotlin`` (``batoulapps/adhan-kotlin``, the maintained adhan2):
  whole-second ``unrounded`` + ``rounded`` values, tier-(a) and tier-(b).
- ``adhanpy`` (``alphahm/adhanpy``, the direct parent): minute-only
  ``rounded`` values, tier-(b) only.

Vectors live in ``tests/benchmark/vectors/`` and are generated by the
``generate_*.py`` scripts in this directory. The harness reads only these
files and imports only the public API plus the unrounded accessor.

Comparison tiers (spec §3.2, with the recorded tier-(b) deviation for
adhanpy's minute-59 rollover):

- tier-(a): the six astronomical prayers, our post-offset pre-round instant
  within 1 s of the port's unrounded value.
- tier-(b): public rounded fields. A single ±60 s flip is accepted only when
  one side's pre-round second is within 1 s of the :30 half-up boundary. For
  minute-only sources, accept exactly adhanpy's documented
  ``replace(minute=60)`` fallback and nothing wider.
"""

import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent))

import grid
from alfalak import (
    CalculationMethod,
    CalculationParameters,
    Coordinates,
    HighLatitudeRule,
    Prayer,
    PrayerTimes,
)
from alfalak.util.DateComponents import DateComponents

ASTRONOMICAL = ("fajr", "sunrise", "dhuhr", "asr", "maghrib", "isha")
PRAYER_BY_NAME = {name: getattr(Prayer, name.upper()) for name in ASTRONOMICAL}

METHOD_MAP = {
    "MUSLIM_WORLD_LEAGUE": CalculationMethod.MUSLIM_WORLD_LEAGUE,
    "NORTH_AMERICA": CalculationMethod.NORTH_AMERICA,
}


def _vector_paths():
    return sorted((Path(__file__).parent / "vectors").glob("*.json"))


def test_vectors_cover_every_pinned_source():
    # The harness must not silently halve its coverage if one vendor file is
    # deleted or mislabeled: every pinned source has exactly one committed
    # vector file, and each file's stem matches its declared ``source``.
    sources = []
    for path in _vector_paths():
        data = json.loads(path.read_text(encoding="utf-8"))
        assert (
            data["source"] == path.stem
        ), f"{path.name} declares source {data['source']!r}"
        sources.append(data["source"])
    assert len(sources) == len(set(sources)), f"duplicate vectors: {sources}"
    expected = set(grid.SOURCE_PINS)
    present = set(sources)
    assert present == expected, (
        f"missing vendored vectors: {sorted(expected - present)}; "
        f"unexpected: {sorted(present - expected)}"
    )


def _build_prayer_times(entry):
    year, month, day = (int(part) for part in entry["date"].split("-"))
    params = CalculationParameters(method=METHOD_MAP[entry["method"]])
    params.high_latitude_rule = HighLatitudeRule.MIDDLE_OF_THE_NIGHT
    return PrayerTimes(
        Coordinates(entry["latitude"], entry["longitude"]),
        DateComponents(year, month, day),
        calculation_parameters=params,
    )


def _to_utc(value):
    if value.tzinfo is None:
        return value.replace(tzinfo=timezone.utc)
    return value.astimezone(timezone.utc)


def _parse_iso_utc(value):
    # Generated vectors are ISO-8601 UTC, either ``...Z`` or ``+00:00``.
    return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(timezone.utc)


def _rounds_up(value):
    return value.second + value.microsecond / 1e6 >= 30


def _boundary_minute_equal(our_rounded, our_unrounded, their_rounded, their_unrounded):
    if our_rounded == their_rounded:
        return True
    if abs((our_rounded - their_rounded).total_seconds()) != 60:
        return False
    # The pre-round instants must be within tier-(a) tolerance and straddle
    # the :30 boundary. If both sit on the same side, at most one of the two
    # rounded minutes can be correct, so a flip is a real mismatch.
    if abs((our_unrounded - their_unrounded).total_seconds()) > 1.0:
        return False
    return _rounds_up(our_unrounded) != _rounds_up(their_unrounded)


def _minute_only_equal(our_rounded, our_unrounded, their_rounded):
    if our_rounded == their_rounded:
        return True
    # adhanpy's CalendarUtil.rounded_minute does
    #   replace(minute=int(minute + round(second / 60)), second=0)
    # which raises ValueError at minute 59 / second >= 30 and then falls
    # back to replace(second=0): it truncates instead of rolling the hour.
    # Accept exactly that artifact and nothing wider.
    return (
        our_unrounded.minute == 59
        and our_unrounded.second >= 30
        and their_rounded == our_unrounded.replace(second=0, microsecond=0)
        and (our_rounded - their_rounded).total_seconds() == 60
    )


def _assert_grid_coverage(data):
    source = data["source"]
    expected = [
        (city, latitude, longitude, date, method)
        for city, latitude, longitude, date in grid.GRID
        for method in grid.METHODS
    ]
    actual = [
        (
            entry["city"],
            entry["latitude"],
            entry["longitude"],
            entry["date"],
            entry["method"],
        )
        for entry in data["entries"]
    ]
    assert actual == expected, f"{source} vectors do not cover the fixed grid"


def _compare_tier_a(source, entry, prayer_times):
    max_delta = 0.0
    for prayer_name in ASTRONOMICAL:
        our_unrounded = prayer_times.time_for_prayer_unrounded(
            PRAYER_BY_NAME[prayer_name]
        )
        their_unrounded = _parse_iso_utc(entry["unrounded"][prayer_name])
        delta = abs((our_unrounded - their_unrounded).total_seconds())
        max_delta = max(max_delta, delta)
        assert delta <= 1.0, (
            f"tier-a {source} {entry['city']} {entry['date']} "
            f"{entry['method']} {prayer_name}: delta={delta:.3f}s"
        )
    return max_delta


def _compare_tier_b(source, entry, prayer_times, minute_only):
    max_delta = 0.0
    for prayer_name in ASTRONOMICAL:
        our_rounded = _to_utc(getattr(prayer_times, prayer_name))
        their_rounded = _to_utc(_parse_iso_utc(entry["rounded"][prayer_name]))
        our_unrounded = prayer_times.time_for_prayer_unrounded(
            PRAYER_BY_NAME[prayer_name]
        )
        if minute_only:
            equal = _minute_only_equal(our_rounded, our_unrounded, their_rounded)
        else:
            their_unrounded = _parse_iso_utc(entry["unrounded"][prayer_name])
            equal = _boundary_minute_equal(
                our_rounded, our_unrounded, their_rounded, their_unrounded
            )
        delta = abs((our_rounded - their_rounded).total_seconds())
        max_delta = max(max_delta, delta)
        assert equal, (
            f"tier-b {source} {entry['city']} {entry['date']} "
            f"{entry['method']} {prayer_name}: "
            f"ours={our_rounded.isoformat()} theirs={their_rounded.isoformat()}"
        )
    return max_delta


@pytest.mark.parametrize(
    "vector_path", _vector_paths(), ids=[path.stem for path in _vector_paths()]
)
def test_cross_port(vector_path):
    data = json.loads(vector_path.read_text(encoding="utf-8"))
    source = data["source"]
    pin = grid.SOURCE_PINS[source]
    assert data["sha"] == pin["sha"], f"{source} vector SHA is not pinned"
    assert data["version"] == pin["version"], f"{source} vector version is not pinned"
    assert (
        data["high_latitude_rule"] == pin["high_latitude_rule"]
    ), f"{source} vector high-latitude rule is not pinned"
    seconds_procedure = data["seconds_procedure"]
    assert (
        seconds_procedure == pin["seconds_procedure"]
    ), f"{source} vector seconds_procedure is not pinned"
    assert seconds_procedure in ("fractional", "second", "minute-only")
    minute_only = seconds_procedure == "minute-only"
    if not minute_only:
        assert (
            "unrounded" in data["entries"][0]
        ), f"{source} declares {seconds_procedure} but has no unrounded values"

    _assert_grid_coverage(data)

    tier_a_max = 0.0
    tier_b_max = 0.0
    for entry in data["entries"]:
        prayer_times = _build_prayer_times(entry)
        if not minute_only:
            tier_a_max = max(tier_a_max, _compare_tier_a(source, entry, prayer_times))
        tier_b_max = max(
            tier_b_max, _compare_tier_b(source, entry, prayer_times, minute_only)
        )

        # syuruk is the sunrise alias; only the rounded field is comparable.
        assert prayer_times.syuruk == prayer_times.sunrise

    print(
        f"{source}: {len(data['entries'])} entries; "
        f"tier-a max delta {tier_a_max:.3f}s; "
        f"tier-b max delta {tier_b_max:.3f}s"
    )
    assert tier_a_max <= 1.0
    assert tier_b_max <= 60.0


def test_vectors_directory_is_not_empty():
    assert _vector_paths(), "no cross-port vectors found; vendored JSON is missing"


def test_boundary_minute_equal_requires_a_boundary_value():
    our_rounded = datetime(2024, 1, 1, 12, 0, tzinfo=timezone.utc)
    their_rounded = datetime(2024, 1, 1, 12, 1, tzinfo=timezone.utc)
    below_boundary = datetime(2024, 1, 1, 12, 0, 29, 500_000, tzinfo=timezone.utc)
    above_boundary = datetime(2024, 1, 1, 12, 0, 30, 500_000, tzinfo=timezone.utc)
    far_from_boundary = datetime(2024, 1, 1, 12, 0, 20, tzinfo=timezone.utc)

    # Opposite sides of :30 justify the one-minute flip.
    assert _boundary_minute_equal(
        our_rounded, below_boundary, their_rounded, above_boundary
    )
    # Both on the same side (even at the boundary) do not.
    assert not _boundary_minute_equal(
        our_rounded, below_boundary, their_rounded, below_boundary
    )
    assert not _boundary_minute_equal(
        our_rounded, above_boundary, their_rounded, above_boundary
    )
    assert not _boundary_minute_equal(
        our_rounded, far_from_boundary, their_rounded, far_from_boundary
    )
    # More than one minute apart is never a rounding flip.
    assert not _boundary_minute_equal(
        our_rounded,
        below_boundary,
        their_rounded + timedelta(minutes=1),
        above_boundary,
    )
    # Outside tier-(a) tolerance, a straddle is not a rounding difference.
    wide_straddle = datetime(2024, 1, 1, 12, 0, 31, tzinfo=timezone.utc)
    assert not _boundary_minute_equal(
        our_rounded, below_boundary, their_rounded, wide_straddle
    )
